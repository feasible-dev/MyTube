import test from 'node:test';
import { selectSearchColumns, uniqueVideos } from './model.mjs';
import assert from 'node:assert/strict';
import { institutionalSignals, youtubeSearchUrl, filterLiveResults, detectLiveStatus, syntheticProductionSignals } from './model.mjs';

test('combining video sources keeps the first record and original order without mutating inputs', () => {
  const first = Object.freeze({ video_id: 'same', title: 'Preferred record' });
  const other = Object.freeze({ video_id: 'other' });
  const candidates = Object.freeze([first, other, { video_id: 'same', title: 'Older record' }, other]);
  assert.deepEqual(uniqueVideos(candidates), [first, other]);
  assert.equal(uniqueVideos(candidates)[0], first);
  assert.equal(candidates.length, 4);
});

test('scroll overflow preserves the first eight cards in each column despite overlapping pools', () => {
  const direct = Array.from({ length: 22 }, (_, i) => ({ video_id: `d${i}`, title: `Direct ${i}`, channel: `Creator ${i}`, source: 'youtube_live', discovery_stream: 'direct' }));
  const related = direct.slice(8, 18).map(v => ({ ...v, discovery_stream: 'adjacent' }));
  const first = selectSearchColumns([...direct, ...related], true);
  const expanded = selectSearchColumns([...direct, ...related], true, 50);
  assert.deepEqual(expanded.direct.slice(0, 8), first.direct);
  assert.deepEqual(expanded.related.slice(0, 8), first.related);
  assert.ok(expanded.direct.length > 8);
  assert.equal(new Set(Object.values(expanded).flat().map(v => v.video_id)).size, Object.values(expanded).flat().length);
});

test('external platform caps leave room for YouTube exploration', () => {
  const videos = ['Vimeo', 'YouTube', 'Rumble'].flatMap(platform => Array.from({ length: 8 }, (_, i) => ({
    video_id: `${platform}${i}`, title: `${platform} film ${i}`, channel: `Creator ${i}`, channel_unknown: platform !== 'YouTube', platform, discovery_stream: 'wildcard',
  })));
  const rows = selectSearchColumns(videos, true).wildcard;
  assert.equal(rows.length, 8); assert.equal(rows.filter(v => v.platform === 'Vimeo').length, 3);
  assert.equal(rows.filter(v => v.platform === 'YouTube').length, 2); assert.equal(rows.filter(v => v.platform === 'Rumble').length, 3);
});

const videos = [
  { video_id: 'a', title: 'Disaster investigation documentary', channel: 'Daily Creator', duration_seconds: 1800 },
  { video_id: 'b', title: 'Engineering seminar', channel: 'Example University', duration_seconds: 3000 },
  { video_id: 'c', title: 'Full trial proceedings', channel: 'Public Record', duration_seconds: 4000 },
  { video_id: 'd', title: 'A conference lecture', channel: 'Independent Lecturer', duration_seconds: 2400 },
];
const state = { search: '', duration: 'all', method: 'diversified', preferInstitutions: true,
  savedOnly: false, saved: new Set(), hidden: new Set() };

test('explicit synthetic production is excluded without treating AI topics or low views as evidence', () => {
  for (const v of [
    { title: 'Rome [AI-generated]' }, { title: 'AI-generated documentary about Rome' },
    { description: 'This video was created using AI tools.' },
    { description: 'This documentary uses synthetic narration.' },
    { description: 'Narration: AI-generated' },
    { description: 'Cette vidéo a été générée par une intelligence artificielle.' },
  ]) {
    assert.ok(syntheticProductionSignals(v).length, JSON.stringify(v));
    assert.equal(filterLiveResults([{ ...videos[0], ...v }], state).length, 0);
  }
  for (const v of [
    { title: 'Lecture on AI and society', views: 0 },
    { title: 'How to detect AI-generated documentaries' },
    { title: 'History of Rome [No AI]', description: 'This video was not generated by AI.' },
    { title: 'A documentary', description: 'This video discusses AI-generated narration.' },
    { description: 'Cette vidéo a été créée sans IA.' },
    { title: 'Why artificial intelligence matters', channel: 'AI Research Institute', views: 8 },
  ]) assert.deepEqual(syntheticProductionSignals(v), [], JSON.stringify(v));
});

test('YouTube search preserves query text inside a single parameter on the fixed origin', () => {
  for (const query of ['openai math dump', 'history & science #trial', 'https://example.org/?x=1', '<script>alert(1)</script>', 'conférences']) {
    const url = new URL(youtubeSearchUrl(query));
    assert.equal(url.origin, 'https://www.youtube.com');
    assert.equal(url.pathname, '/results');
    assert.deepEqual([...url.searchParams], [['search_query', query]]);
    assert.equal(url.hash, '');
  }
  for (const value of ['', '  ', null, 'a'.repeat(301)]) assert.throws(() => youtubeSearchUrl(value), /INVALID_QUERY/);
});

test('source preference distinguishes formats from generic disaster commentary', () => {
  assert.equal(institutionalSignals(videos[0]).length, 0);
  assert.equal(institutionalSignals(videos[1]).length, 2);
  assert.equal(institutionalSignals(videos[2]).length, 1);
  assert.equal(institutionalSignals({ title: 'College scandal commentary', channel: 'Random Creator' }).length, 0);
  assert.equal(institutionalSignals({ title: 'History', channel: 'Royal Institution' }).length, 1);
});

test('live filtering preserves provider relevance without requiring literal query matches', () => {
  const rows = videos.map((v, i) => ({ ...v, provider_rank: i + 1 }));
  assert.deepEqual(filterLiveResults(rows, { ...state, preferInstitutions: false }).map(v => v.video_id), ['a', 'b', 'c', 'd']);
  assert.deepEqual(filterLiveResults(rows, state).map(v => v.video_id), ['b', 'c', 'd', 'a']);
  assert.deepEqual(filterLiveResults(rows, { ...state, duration: 'long', hidden: new Set(['b']) }).map(v => v.video_id), ['d']);
  assert.deepEqual(filterLiveResults(rows, { ...state, savedOnly: true, saved: new Set(['a']) }).map(v => v.video_id), ['a']);
});

test('live diagnostics distinguish a local file, missing module, stale context and configured extension', () => {
  const api = { runtime: { id: 'public-id', getManifest: () => ({ version: '0.3.1', oauth2: { client_id: 'public-client-id' } }) } };
  assert.equal(detectLiveStatus(null, api, 'file:').reason, 'EXTENSION_REQUIRED');
  assert.equal(detectLiveStatus(null, api, 'chrome-extension:').reason, 'LIVE_MODULE_UNAVAILABLE');
  const ready = detectLiveStatus({ status: () => ({ ready: true, reason: null }) }, api, 'chrome-extension:');
  assert.equal(ready.ready, true); assert.equal(ready.clientConfigured, true); assert.equal(ready.version, '0.3.1');
  const stale = detectLiveStatus({ status: () => { throw new Error('private provider detail'); } }, api, 'chrome-extension:');
  assert.equal(stale.reason, 'RELOAD_REQUIRED');
  assert.ok(!JSON.stringify(stale).includes('private provider detail'));
});

test('duration sliders include exact endpoints and reject inverted or out-of-range settings', () => {
  const rows = videos.map((v, i) => ({ ...v, provider_rank: i + 1 }));
  assert.deepEqual(filterLiveResults(rows, { ...state, minMinutes: 40, maxMinutes: 50 }).map(v => v.video_id), ['b', 'd']);
  for (const [minMinutes, maxMinutes] of [[50, 40], [0, 120], [20, 361], [NaN, 100]]) {
    assert.throws(() => filterLiveResults(rows, { ...state, minMinutes, maxMinutes }), /INVALID_FILTER/);
  }
});
